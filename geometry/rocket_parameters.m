function [profile_rot] = global_rotate(profile_in,index_center,angle_deg)

% Z Rotation profile 1-----------------------------------------------------
Rx = [1 0 0; 0 cosd(angle_deg(1)), -sind(angle_deg(1)); 0 sind(angle_deg(1)), cosd(angle_deg(1))];
