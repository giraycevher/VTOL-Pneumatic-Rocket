%% Function to calculate class and shape function
% function [y] = ClassShape(w,x,N1,N2,dz);
function [y,S] = ClassShape(w,x,N1,N2,dz);


% Class function; taking input of N1 and N2
for i = 1:size(x,1)
    C(i,1) = x(i)^N1*((1-x(i))^N2);
end

% Shape function; using Bernstein Polynomials
n = size(w,2)-1; % Order of Bernstein polynomials

for i = 1:n+1
     K(i) = factorial(n)/(factorial(i-1)*(factorial((n)-(i-1))));
end

for i = 1:size(x,1)
    S(i,1) = 0;
    for j = 1:n+1
        S(i,1) = S(i,1) + w(j)*K(j)*x(i)^(j-1)*((1-x(i))^(n-(j-1)));

    end
end

% Calculate y output
for i = 1:size(x,1)
   y(i,1) = C(i,1)*S(i,1) + x(i)*dz;
end


end


function P_out = correct3DProfile(P, desired_order, n, start_index)
% correct3DProfile - Reorders a 3D closed profile based on normal and start node
%
% Inputs:
%   P             - Nx3 matrix of 3D coordinates (closed or open)
%   desired_order - 'ccw' or 'cw' (desired polygon orientation)
%   n             - 1x3 unit normal vector (e.g., [1 0 0])
%   start_index   - Index of the node you want as starting point (1-based)
%                   for input profile
%
% Output:
%   P_out         - (N+1)x3 matrix of reordered and closed profile


    % Rotate so start_index becomes the first
    P = [P(start_index:end, :); P(1:start_index-1, :)];



    % Ensure P is closed
    if any(P(1,:) ~= P(end,:))
        P = [P; P(1,:)];  % Close the loop
    end

    % Create 2D local basis perpendicular to the normal vector
    if all(n == [1 0 0])
        temp = [0 1 0];
    else
        temp = [1 0 0];
    end
    u = cross(n, temp); u = u / norm(u);
    v = cross(n, u);    v = v / norm(v);

    % Project to 2D using the local u-v plane
    proj2D = [(P * u'), (P * v')];
    x = proj2D(:,1);
    y = proj2D(:,2);

    % Compute signed area (shoelace formula)
    area = 0.5 * sum(x(1:end-1).*y(2:end) - x(2:end).*y(1:end-1));

    % Reverse order if it doesn't match desired orientation
    if (strcmpi(desired_order, 'ccw') && area < 0) || ...
       (strcmpi(desired_order, 'cw') && area > 0)
        P = flipud(P);
    end

    % Remove duplicate last point before rotating
    P = P(1:end-1, :);

    % Ensure start_index is valid
    N = size(P,1);
    if start_index < 1 || start_index > N
        error('start_index must be between 1 and %d', N);
    end


    % Close the loop
    P_out = [P; P(1,:)];
end



